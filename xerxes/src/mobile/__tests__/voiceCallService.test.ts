import { describe, expect, it, vi } from 'vitest'

import { createMemoryRouter } from '../routes.js'
import { voiceOrbLevel, voiceStateLine } from '../voice/call/presentation.js'
import { VoiceCallService } from '../voice/call/service.js'
import { voiceServiceFixture } from './voiceCallServiceFakes.js'

describe('app-owned voice session', () => {
  it('opens settings/status without acquiring the microphone, then starts only on a gesture', async () => {
    const f = voiceServiceFixture()
    f.service.open()
    expect(f.service.getSnapshot().view).toBe('voice')
    expect(f.createEngine).not.toHaveBeenCalled()
    await f.service.loadStatus()
    await f.service.start()
    expect(f.beforeStart).toHaveBeenCalledOnce()
    expect(f.engine.start).toHaveBeenCalledWith('standard')
    expect(f.service.getSnapshot().call.phase).toBe('listening')
    f.service.dispose()
  })
  it('Chat/minimize, tab navigation and return-to-voice reuse the same running engine without hanging up', async () => {
    const f = voiceServiceFixture()
    const router = createMemoryRouter('/xerxes')
    await f.service.loadStatus()
    await f.service.start()
    f.service.minimize()
    expect(f.service.getSnapshot()).toMatchObject({ view: 'chat', call: { phase: 'listening' } })
    router.navigate({ name: 'usage' })
    f.emit({ phase: 'speaking', spokenSentence: 'Still speaking while you browse.' })
    router.navigate({ name: 'xerxes' })
    expect(f.service.getSnapshot().call.spokenSentence).toBe('Still speaking while you browse.')
    f.service.open()
    expect(f.service.getSnapshot()).toMatchObject({ view: 'voice', call: { phase: 'speaking' } })
    expect(f.engine.hangup).not.toHaveBeenCalled()
    expect(f.engine.start).toHaveBeenCalledOnce()
    expect(f.createEngine).toHaveBeenCalledOnce()
    f.service.end()
    expect(f.engine.hangup).toHaveBeenCalledOnce()
    expect(f.service.getSnapshot().view).toBe('closed')
    f.service.dispose()
  })
  it('Mute and orb interrupt affect the engine but do not end its session', async () => {
    const f = voiceServiceFixture()
    await f.service.loadStatus()
    await f.service.start()
    f.service.mute()
    expect(f.engine.mute).toHaveBeenCalledWith(true)
    f.emit({ phase: 'speaking' })
    f.service.interrupt()
    expect(f.engine.interrupt).toHaveBeenCalledOnce()
    expect(f.engine.hangup).not.toHaveBeenCalled()
    expect(f.service.getSnapshot().call.phase).toBe('listening')
    f.service.dispose()
  })
  it('does not end on a connection/view update, forwards hidden state and closes when the engine ends', async () => {
    const f = voiceServiceFixture()
    await f.service.loadStatus()
    await f.service.start()
    f.service.minimize()
    f.service.setConnected(false)
    expect(voiceStateLine(f.service.getSnapshot())).toBe('Connecting')
    expect(f.engine.hangup).not.toHaveBeenCalled()
    f.service.visibility(true)
    expect(f.engine.visibility).toHaveBeenCalledWith(true)
    f.emit({ phase: 'idle', notice: 'Call ended after the tab was hidden for 60 seconds.' })
    expect(f.service.getSnapshot().view).toBe('closed')
    f.emit({ phase: 'error', error: 'A real microphone error.' })
    expect(f.service.getSnapshot().view).toBe('voice')
    f.service.dispose()
  })
  it('keeps tier selection stable during a running call and disposes only at app teardown', async () => {
    const f = voiceServiceFixture()
    await f.service.loadStatus()
    f.service.setTier('light')
    await f.service.start()
    f.service.setTier('standard')
    expect(f.service.getSnapshot().tier).toBe('light')
    expect(f.engine.start).toHaveBeenCalledWith('light')
    f.service.dispose()
    expect(f.engine.hangup).toHaveBeenCalledOnce()
  })
  it('surfaces unavailable models without constructing a fake successful engine', async () => {
    const create = vi.fn(() => { throw new Error('not reached') })
    const service = new VoiceCallService({ engine: create, canStart: () => true, modelsStatus: async () => { throw new Error('Call models unavailable.') } })
    await service.loadStatus()
    await service.start()
    expect(service.getSnapshot().error).toBe('Call models unavailable.')
    expect(create).not.toHaveBeenCalled()
    service.dispose()
  })
  it('restores/persists only the opt-in preference and applies it to the engine without ending the call', async () => {
    const f = voiceServiceFixture()
    const remember = vi.fn()
    const service = new VoiceCallService({ engine: f.createEngine, modelsStatus: f.modelsStatus, canStart: () => true, debugEnabled: () => true, rememberDebugEnabled: remember })
    expect(service.getSnapshot().debugCaptureEnabled).toBe(true)
    expect(f.createEngine).not.toHaveBeenCalled()
    await service.loadStatus()
    await service.start()
    expect(f.engine.setDebugCaptureEnabled).toHaveBeenCalledWith(true)
    service.setDebugCaptureEnabled(false)
    expect(remember).toHaveBeenCalledWith(false)
    expect(f.engine.setDebugCaptureEnabled).toHaveBeenCalledWith(false)
    expect(service.getSnapshot().debugCaptureEnabled).toBe(false)
    expect(f.engine.hangup).not.toHaveBeenCalled()
    service.end()
    expect(service.getSnapshot().call.debugCapture).toBeUndefined()
    service.dispose()
  })
  it('selects live mic versus output levels, clamps them, and never changes engine state', () => {
    const f = voiceServiceFixture()
    const base = f.service.getSnapshot()
    expect(voiceOrbLevel({ ...base, call: { ...base.call, phase: 'hearing', inputLevel: 0.6, outputLevel: 0.1 } })).toBe(0.6)
    expect(voiceOrbLevel({ ...base, call: { ...base.call, phase: 'speaking', inputLevel: 0.6, outputLevel: 0.2 } })).toBe(0.2)
    expect(voiceOrbLevel({ ...base, call: { ...base.call, phase: 'hearing', inputLevel: 4 } })).toBe(1)
    expect(voiceOrbLevel({ ...base, call: { ...base.call, inputLevel: NaN } })).toBe(0)
    expect(voiceOrbLevel({ ...base, call: { ...base.call, muted: true, inputLevel: 0.8 } })).toBe(0)
    expect(f.engine.start).not.toHaveBeenCalled()
  })
})
